#!/usr/bin/env python3
"""Write an OMNI file of every Terra Fusion granule under one bucket path.

    python3 tf_make_omni.py P108 > ../../omni/terra_fusion_p108.omni.yaml

Lists s3://terrafusiondatasampler/<path>/ with unsigned ListObjectsV2 requests
(set https_proxy on a compute node), drops objects under MIN_BYTES (the bucket
holds 2,176-byte stubs that are not HDF5 granules), and writes the transfers
largest first, as omni/terra_fusion.omni.yaml does.
"""
import os, sys, urllib.parse, urllib.request
import xml.etree.ElementTree as ET

BUCKET = 'terrafusiondatasampler'
URL = f'https://{BUCKET}.s3.us-west-2.amazonaws.com/'
NS = {'s': 'http://s3.amazonaws.com/doc/2006-03-01/'}
MIN_BYTES = int(os.environ.get('MIN_BYTES', 100_000_000))


def list_prefix(prefix):
    token, out = None, []
    while True:
        q = {'list-type': '2', 'prefix': prefix, 'max-keys': '1000'}
        if token:
            q['continuation-token'] = token
        with urllib.request.urlopen(URL + '?' + urllib.parse.urlencode(q)) as r:
            root = ET.fromstring(r.read())
        for c in root.findall('s:Contents', NS):
            out.append((c.find('s:Key', NS).text, int(c.find('s:Size', NS).text)))
        t = root.find('s:NextContinuationToken', NS)
        if t is None:
            return out
        token = t.text


def main():
    path = sys.argv[1].strip('/')
    objs = [o for o in list_prefix(path + '/') if o[0].endswith('.h5')]
    keep = sorted((o for o in objs if o[1] >= MIN_BYTES), key=lambda o: -o[1])
    drop = sorted(o for o in objs if o[1] < MIN_BYTES)
    total = sum(s for _, s in keep)
    w = sys.stdout.write
    w('# OMNI\n')
    w(f'name: terra_fusion_{path.lower()}\n')
    w('tags: aws,terrafusion,public-data\n\n')
    w(f'# Every Terra Fusion granule under s3://{BUCKET}/{path}/ (us-west-2, public),\n')
    w(f'#   generated by src/tf/tf_make_omni.py {path}: {len(keep)} objects, '
      f'{total / 1e9:,.1f} GB. Largest first.\n')
    w(f'#   Left out (under {MIN_BYTES:,} bytes, not usable granules):\n')
    for k, s in drop:
        w(f'#     {k}  {s:,} bytes\n')
    w('#   Destination, environment and transfer tuning: as in terra_fusion.omni.yaml.\n')
    w('#   Run with ../pbs/tf_p108.pbs (several nodes, rolling delete), not\n')
    w('#   tf_congruence.pbs alone: this does not fit in one node\'s memory.\n\n')
    w('transfers:\n')
    for k, s in keep:
        name = k.rsplit('/', 1)[1]
        w(f'  - src: "s3://{BUCKET}/{k}"   # {s:,} bytes\n')
        w(f'    dst: "cfs::/terra_fusion/{name}"\n')
        w('    format: "binary"\n')


if __name__ == '__main__':
    main()
